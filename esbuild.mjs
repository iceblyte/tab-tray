import { builtinModules } from 'node:module';
import process from 'node:process';
import esbuild from 'esbuild';
import sveltePlugin from 'esbuild-svelte';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
		...builtinModules.map((m) => `node:${m}`),
	],
	format: 'cjs',
	target: 'es2022',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	mainFields: ['svelte', 'browser', 'module', 'main'],
	conditions: ['svelte', 'browser'],
	plugins: [
		sveltePlugin({
			compilerOptions: {
				// Runes only: no legacy `export let` / reactive statements.
				runes: true,
				// Obsidian loads a single styles.css; component styles must not
				// leak into a separate main.css bundle.
				css: 'injected',
			},
		}),
	],
});

if (prod) {
	await context.rebuild();
	await context.dispose();
} else {
	await context.watch();
}
